function structures(bone: string, rows: string): Structure[] {
  return rows
    .trim()
    .split("\n")
    .map((line, i) => {
      const [name, latin, category, note] = line
        .split("|")
        .map((s) => s.trim());
      return { id: `${bone}-${i + 1}`, name, latin, category, note };
    });
}

