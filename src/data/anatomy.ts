export const normalize = (value: string) =>
  value.toLocaleLowerCase("ru").replaceAll("ё", "е").trim();
export function matchesBone(b: Bone, query: string) {
  const q = normalize(query);
  return (
    !q ||
    normalize(
      `${b.name} ${b.latin} ${b.structures.map((s) => `${s.name} ${s.latin}`).join(" ")}`,
    ).includes(q)
  );
}
